-- Apply ONLY after the authenticated API is deployed. Until then the old API
-- uses service-role access and exposes database writes publicly.
create table if not exists public.app_data (
  key text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.visitors (
  id bigint generated by default as identity primary key,
  ip text, city text, region text, country text,
  visited_at timestamptz not null default now()
);
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  event text not null, payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.match_votes (
  id bigint generated by default as identity primary key,
  match_id text not null, voter_id text not null,
  choice text not null check (choice in ('home','draw','away')),
  unique (match_id, voter_id)
);
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique, p256dh text not null, auth text not null,
  user_agent text not null default ''
);
create table if not exists public.admin_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create index if not exists visitors_visited_at_idx on public.visitors (visited_at desc);
create index if not exists notifications_created_at_idx on public.notifications (created_at);
alter table public.app_data enable row level security;
alter table public.visitors enable row level security;
alter table public.notifications enable row level security;
alter table public.match_votes enable row level security;
alter table public.push_subscriptions enable row level security;
alter table public.admin_accounts enable row level security;
-- No anon/authenticated access to tables: the authenticated server mediates all
-- access, and the allowlist itself is never client-writable.
revoke all on public.app_data, public.visitors, public.notifications, public.match_votes, public.push_subscriptions, public.admin_accounts from anon, authenticated;

-- Storage images are public by design; upload, update, and deletion require an
-- allowlisted Supabase Auth account with a verified email.
create or replace function public.is_app_admin() returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.admin_accounts a
    join auth.users u on u.id = a.user_id
    where a.user_id = (select auth.uid()) and u.email_confirmed_at is not null
  );
$$;
revoke all on function public.is_app_admin() from public;
grant execute on function public.is_app_admin() to authenticated;
insert into storage.buckets (id, name, public) values ('media', 'media', true) on conflict (id) do nothing;
drop policy if exists "Admin media insert" on storage.objects;
create policy "Admin media insert" on storage.objects for insert to authenticated with check (bucket_id = 'media' and public.is_app_admin());
drop policy if exists "Admin media update" on storage.objects;
create policy "Admin media update" on storage.objects for update to authenticated using (bucket_id = 'media' and public.is_app_admin()) with check (bucket_id = 'media' and public.is_app_admin());
drop policy if exists "Admin media delete" on storage.objects;
create policy "Admin media delete" on storage.objects for delete to authenticated using (bucket_id = 'media' and public.is_app_admin());
drop policy if exists "Admin media select" on storage.objects;
create policy "Admin media select" on storage.objects for select to authenticated using (bucket_id = 'media' and public.is_app_admin());
grant all on public.app_data, public.visitors, public.notifications, public.match_votes, public.push_subscriptions, public.admin_accounts to service_role;
grant usage, select on all sequences in schema public to service_role;
